    async def ensure_timeline(
        self,
        client,
        group_id: int,
        limit: int,
    ) -> bool:
        """
        اگر Timeline گروه وجود نداشته باشد،
        فقط یک بار آن را Load می‌کند.

        برای جلوگیری از Load همزمان توسط چند Event،
        برای هر گروه Lock جداگانه داریم.
        """

        if group_id in self._timelines:
            return False

        lock = self._timeline_load_locks.setdefault(
            group_id,
            asyncio.Lock(),
        )

        async with lock:
            # ممکن است Event دیگری قبل از ما Timeline را ساخته باشد.
            if group_id in self._timelines:
                return False

            await self.load_timeline(
                client,
                group_id,
                limit,
            )

            return True


    async def get_current_reply_context(
        self,
        event,
    ) -> str | None:
        """
        رابطه Reply پیام جاری را مستقیماً از خود Event می‌گیرد.
        این اطلاعات مستقل از Timeline است.
        """

        if not getattr(event, "is_reply", False):
            return None

        try:
            replied = await event.get_reply_message()
        except Exception as exc:
            print(
                f"⚠️ خطا در دریافت پیام Reply شده: {exc}"
            )
            return None

        if replied is None:
            return None

        message_id = self._extract_message_id(
            replied
        )

        if message_id is None:
            return None

        sender_id = getattr(
            replied,
            "sender_id",
            None,
        )

        if sender_id is not None:
            try:
                sender_id = int(sender_id)
            except Exception:
                sender_id = None

        sender_identity = await self._resolve_sender_identity(
            event.chat_id,
            replied,
            sender_id,
        )

        sender_name = (
            sender_identity.get("nick_name")
            or sender_identity.get("user_name")
            or (
                str(sender_id)
                if sender_id is not None
                else "نامشخص"
            )
        )

        text = self._extract_timeline_text(replied)

        if len(text) > 1200:
            text = text[:1200] + "..."

        date = self._format_date(
            getattr(
                replied,
                "date",
                None,
            )
        )

        return (
            "📌 اطلاعات قطعی Reply پیام جاری:\n"
            "پیام فعلی مستقیماً به پیام زیر Reply شده است.\n\n"
            f"فرستنده پیام هدف: {sender_name}\n"
            f"شناسه فرستنده: {sender_id}\n"
            f"شناسه پیام هدف: {message_id}\n"
            f"زمان پیام هدف: {date}\n"
            f"متن پیام هدف:\n{text}\n\n"
            "این رابطه را حدس نزن؛ این پیام مستقیماً "
            "به پیام بالا Reply شده است."
        )


    async def maybe_trim(
        self,
        group_id: int,
    ) -> None:
        self._trim_counters[group_id] += 1

        if self._trim_counters[group_id] < self.TRIM_EVERY_MESSAGES:
            return

        self._trim_counters[group_id] = 0

        await self.trim(group_id)

    def _select_messages(
        self,
        rows: list[dict],
        system_prompt: str,
        token_limit: int,
        model_name: str | None,
    ) -> list[dict[str, str]]:
        """
        پیام‌ها را از جدیدترین به قدیمی‌ترین انتخاب می‌کند
        تا سقف توکن پر شود.
        """

        counter_ok = model_name is not None

        def count(text: str) -> int:
            nonlocal counter_ok

            if counter_ok:
                try:
                    return (
                        int(
                            token_counter(
                                model=model_name,
                                text=text,
                            )
                        )
                        + self.MESSAGE_OVERHEAD_TOKENS
                    )
                except Exception as exc:
                    print(
                        f"⚠️ خطا در محاسبه توکن حافظه: {exc}"
                    )
                    counter_ok = False

            return (
                max(1, len(text) // 4)
                + self.MESSAGE_OVERHEAD_TOKENS
            )

        total = count(system_prompt)
        selected: list[dict[str, str]] = []

        for row in reversed(rows):
            cost = count(row["content"])

            if selected and total + cost > token_limit:
                break

            selected.append(
                {
                    "role": row["role"],
                    "content": row["content"],
                }
            )

            total += cost

        selected.reverse()

        if (
            selected
            and selected[0]["role"] == "assistant"
        ):
            selected.pop(0)

        return [
            {
                "role": "system",
                "content": system_prompt,
            },
            *selected,
        ]

