    def _format_content_block(
        self,
        text: str,
        media_type: str | None,
    ) -> str:
        parts = []

        if media_type:
            parts.append(
                f'<media type="{self._timeline_attribute(media_type)}" />'
            )

        if text:
            parts.append(f"<text>\n{text}\n</text>")

        return "\n".join(parts)


    @staticmethod
    def _is_command_message(
        message: Any,
    ) -> bool:
        message = AIMemoryManager._unwrap_message(
            message
        )

        raw_text = getattr(
            message,
            "raw_text",
            None,
        )

        if isinstance(raw_text, str):
            return raw_text.strip().startswith("!")

        message_text = getattr(
            message,
            "message",
            None,
        )

        if isinstance(message_text, str):
            return message_text.strip().startswith("!")

        return False





    @staticmethod
    def _unwrap_message(
        message: Any,
    ) -> Any:
        """
        اگر ورودی یک SPlusthon NewMessage.Event باشد،
        Message واقعی داخل event.message قرار دارد.
        اگر خود Message داده شده باشد، همان را برمی‌گردانیم.
        """

        nested = getattr(
            message,
            "message",
            None,
        )

        # NewMessage.Event -> Message
        if (
            nested is not None
            and not isinstance(nested, str)
            and (
                hasattr(nested, "id")
                or hasattr(nested, "media")
                or hasattr(nested, "raw_text")
            )
        ):
            return nested

        return message

    
    @staticmethod
    def _extract_message_content(
        message: Any,
    ) -> tuple[str, str | None]:
        """
        (text, media_type) را جدا برمی‌گرداند.
        media_type فقط وقتی مقدار دارد که پیام واقعاً رسانه داشته باشد؛
        متنی که خودِ کاربر تایپ کرده هیچ‌وقت media_type نمی‌گیرد.
        """

        message = AIMemoryManager._unwrap_message(message)

        text = getattr(message, "message", None)
        if not isinstance(text, str):
            text = ""
        text = text.strip()

        media = getattr(message, "media", None)
        media_type = (
            AIMemoryManager._get_media_type(media)
            if media is not None
            else None
        )

        if media_type is None and not text:
            text = "[پیام بدون متن یا رسانه]"

        return text, media_type
    
    @staticmethod
    def _get_media_type(media: Any) -> str | None:
        if media is None:
            return None

        media_name = type(media).__name__.lower()

        if "photo" in media_name:
            return "photo"

        if "document" not in media_name:
            if "contact" in media_name:
                return "contact"
            if "geo" in media_name:
                return "location"
            if "poll" in media_name:
                return "poll"
            if "webpage" in media_name:
                return "link"
            return "media"

        document = getattr(media, "document", None)

        if document is None:
            return "file"

        mime_type = (getattr(document, "mime_type", None) or "").lower()
        attributes = getattr(document, "attributes", None) or []
        attribute_names = {type(a).__name__.lower() for a in attributes}

        if any("sticker" in name for name in attribute_names):
            return "sticker"

        if any("audio" in name for name in attribute_names):
            for attribute in attributes:
                if "audio" in type(attribute).__name__.lower():
                    if getattr(attribute, "voice", False):
                        return "voice"
            return "audio"

        if (
            mime_type in {"image/gif", "video/gif"}
            or (
                any("animated" in name for name in attribute_names)
                and mime_type.startswith("video/")
            )
        ):
            return "gif"

        if any("video" in name for name in attribute_names):
            return "video"

        if mime_type.startswith("image/"):
            return "photo"
        if mime_type.startswith("video/"):
            return "video"
        if mime_type.startswith("audio/"):
            return "audio"

        return "file"

    @staticmethod
    def _format_date(value: Any) -> str:
        if value is None:
            return "زمان نامشخص"

        try:
            return format_project_time(
                value
            )
        except Exception:
            return str(value)
    @staticmethod
    def _get_sender_identity(
        entity: Any,
        user_id: int | None,
    ) -> dict[str, Any]:
        identity: dict[str, Any] = {}

        if user_id is not None:
            identity["user_id"] = int(user_id)

        if entity is None:
            return identity

        first_name = (
            getattr(
                entity,
                "first_name",
                None,
            )
            or ""
        ).strip()

        last_name = (
            getattr(
                entity,
                "last_name",
                None,
            )
            or ""
        ).strip()

        nick_name = " ".join(
            part
            for part in (
                first_name,
                last_name,
            )
            if part
        ).strip()

        if nick_name:
            identity["nick_name"] = nick_name

        username = (
            getattr(
                entity,
                "username",
                None,
            )
            or ""
        ).strip().lstrip("@")

        if username:
            identity["user_name"] = username

        return identity
    @staticmethod
    def _extract_message_id(message: Any) -> int | None:
        value = getattr(
            message,
            "id",
            None,
        )

        if value is None:
            value = getattr(
                message,
                "message_id",
                None,
            )

        if value is None:
            return None

        try:
            return int(value)
        except Exception:
            return None

    async def _extract_reply_id(
        self,
        message: Any,
    ) -> int | None:

        direct = getattr(
            message,
            "reply_to_msg_id",
            None,
        )

        if direct is not None:
            try:
                return int(direct)
            except Exception:
                pass

        reply_to = getattr(
            message,
            "reply_to",
            None,
        )

        if reply_to is not None:
            possible = (
                getattr(
                    reply_to,
                    "reply_to_msg_id",
                    None,
                )
                or getattr(
                    reply_to,
                    "msg_id",
                    None,
                )
            )

            if possible is not None:
                try:
                    return int(possible)
                except Exception:
                    pass

        # fallback مطمئن‌تر برای نسخه‌هایی که
        # reply_to_msg_id را مستقیم expose نمی‌کنند
        try:
            is_reply = bool(
                getattr(
                    message,
                    "is_reply",
                    False,
                )
            )

            if is_reply and hasattr(
                message,
                "get_reply_message",
            ):
                replied = await message.get_reply_message()

                if replied is not None:
                    return self._extract_message_id(
                        replied
                    )

        except Exception:
            pass

        return None



    async def _get_reply_message(
        self,
        message: Any,
    ) -> Any | None:
        """
        خود پیام Reply شده را برمی‌گرداند.

        این متد فقط برای ساخت reply_preview استفاده می‌شود.
        هیچ فیلتری روی متن پیام هدف انجام نمی‌دهد.
        """
        try:
            getter = getattr(
                message,
                "get_reply_message",
                None,
            )

            if not callable(getter):
                return None

            return await getter()

        except Exception:
            return None

    async def _build_reply_preview(
        self,
        group_id: int,
        target,
    ) -> dict[str, Any] | None:
        """
        اطلاعات کامل پیام Reply شده را برای preview ذخیره می‌کند.

        توجه:
        - هیچ محتوایی به خاطر ! یا Secret حذف نمی‌شود.
        - متن کامل پیام در RAM نگه داشته می‌شود.
        """

        message_id = self._extract_message_id(
            target
        )

        if message_id is None:
            return None

        sender_id = getattr(
            target,
            "sender_id",
            None,
        )

        if sender_id is not None:
            try:
                sender_id = int(sender_id)
            except Exception:
                sender_id = None

        sender_identity = await self._resolve_sender_identity(
            group_id,
            target,
            sender_id,
        )

        text, media_type = self._extract_message_content(target)

        return {
            "message_id": message_id,
            **sender_identity,
            "type": self._get_timeline_message_type(
                sender_id
            ),
            "text": text,
            "media": media_type,
            "date": self._format_date(
                getattr(
                    target,
                    "date",
                    None,
                )
            ),
        }



    def _insert_timeline_record(
        self,
        group_id: int,
        record: dict[str, Any],
    ) -> None:
        timeline = self._timelines[group_id]
        seen = self._timeline_seen.setdefault(
            group_id,
            set(),
        )

        if timeline.maxlen is None:
            return

        message_id = int(record["message_id"])

        # رکورد تکراری
        if message_id in seen:
            return

        records = list(timeline)

        # پیدا کردن جای درست بر اساس message_id
        insert_at = len(records)

        for index, existing in enumerate(records):
            try:
                existing_id = int(
                    existing["message_id"]
                )
            except (
                TypeError,
                ValueError,
            ):
                continue

            if message_id < existing_id:
                insert_at = index
                break

        records.insert(
            insert_at,
            record,
        )

        # اگر از سقف عبور کرد، قدیمی‌ترین رکورد حذف شود.
        if len(records) > timeline.maxlen:
            records = records[-timeline.maxlen:]

        self._timelines[group_id] = deque(
            records,
            maxlen=timeline.maxlen,
        )

        self._timeline_seen[group_id] = {
            int(item["message_id"])
            for item in records
        }


    async def _resolve_sender_identity(
        self,
        group_id: int,
        message: Any,
        sender_id: int | None,
    ) -> dict[str, Any]:

        if sender_id is None:
            return {}

        cache = self._timeline_sender_cache.setdefault(
            group_id,
            {},
        )

        cached = cache.get(sender_id)

        if cached is not None:
            return dict(cached)

        sender = None

        try:
            sender = getattr(
                message,
                "sender",
                None,
            )
        except Exception:
            sender = None

        if sender is None:
            try:
                sender = await message.get_sender()
            except Exception:
                sender = None

        identity = self._get_sender_identity(
            sender,
            sender_id,
        )

        cache[sender_id] = identity

        return dict(identity)


    async def load_timeline(
        self,
        client,
        group_id: int,
        limit: int,
    ) -> int:
        """
        آخرین پیام‌های گروه را از Soroush گرفته
        و در RAM آماده می‌کند.

        Commandها همچنان به‌عنوان رکورد مستقل Timeline
        ذخیره نمی‌شوند.

        اما اگر پیام دیگری به یک Command یا هر پیام دیگری
        که خارج از Timeline فعلی است Reply کرده باشد،
        اطلاعات پیام هدف در reply_preview ذخیره می‌شود.
        """

        limit = max(
            1,
            min(
                int(limit),
                self.MAX_TIMELINE_MESSAGES,
            ),
        )

        messages = await client.get_messages(
            group_id,
            limit=limit,
        )

        if messages is None:
            messages = []

        if not isinstance(
            messages,
            (list, tuple),
        ):
            messages = [messages]

        messages = list(messages)

        # تمام پیام‌های دریافت‌شده، حتی Commandها،
        # اینجا نگه داشته می‌شوند تا بتوانیم Reply هدف
        # را از بین آن‌ها پیدا کنیم.
        fetched_messages_by_id: dict[int, Any] = {}

        for message in messages:
            message_id = self._extract_message_id(
                message
            )

            if message_id is not None:
                fetched_messages_by_id[
                    message_id
                ] = message

        records: list[dict[str, Any]] = []

        # برای اینکه اگر target خارج از Timeline فعلی بود،
        # خود Message مربوط به رکورد را داشته باشیم.
        source_messages_by_id: dict[int, Any] = {}

        # get_messages معمولاً جدیدترین -> قدیمی‌ترین برمی‌گرداند
        for message in reversed(messages):

            message_id = self._extract_message_id(
                message
            )

            if message_id is None:
                continue

            if self._is_command_message(message):
                continue

            text, media_type = self._extract_message_content(message)

            sender_id = getattr(
                message,
                "sender_id",
                None,
            )

            if sender_id is not None:
                try:
                    sender_id = int(sender_id)
                except Exception:
                    sender_id = None

            sender_identity = await self._resolve_sender_identity(
                group_id,
                message,
                sender_id,
            )

            reply_to_id = await self._extract_reply_id(
                message
            )

            record = {
                "message_id": message_id,
                "group_id": group_id,
                **sender_identity,
                "type": self._get_timeline_message_type(
                    sender_id
                ),
                "text": text,
                "media": media_type,
                "date": self._format_date(
                    getattr(
                        message,
                        "date",
                        None,
                    )
                ),
                "reply_to_id": reply_to_id,
            }

            records.append(record)
            source_messages_by_id[
                message_id
            ] = message

        # سقف Timeline
        records = records[-limit:]

        # شناسه‌هایی که واقعاً در Timeline قرار گرفته‌اند
        timeline_ids = {
            int(record["message_id"])
            for record in records
        }

        # برای هر Reply که target خودش در Timeline نیست،
        # preview می‌سازیم.
        for record in records:
            reply_to_id = record.get(
                "reply_to_id"
            )

            if reply_to_id is None:
                continue

            try:
                reply_to_id = int(reply_to_id)
            except Exception:
                continue

            # اگر خود target داخل Timeline است،
            # formatter همان رکورد اصلی را استفاده می‌کند.
            if reply_to_id in timeline_ids:
                continue

            source_message = source_messages_by_id.get(
                int(record["message_id"])
            )

            if source_message is None:
                continue

            # اول در همان batch دریافت‌شده دنبالش می‌گردیم.
            # این حالت مخصوصاً Commandهای حذف‌شده از Timeline است.
            target = fetched_messages_by_id.get(
                reply_to_id
            )

            # اگر در batch نبود، مستقیم از Reply می‌گیریمش.
            if target is None:
                target = await self._get_reply_message(
                    source_message
                )

            if target is None:
                continue

            preview = await self._build_reply_preview(
                group_id,
                target,
            )

            if preview is not None:
                record["reply_preview"] = preview

        timeline = deque(
            records,
            maxlen=limit,
        )

        self._timelines[group_id] = timeline

        self._timeline_seen[group_id] = {
            int(record["message_id"])
            for record in records
        }

        self._timeline_sender_cache.setdefault(
            group_id,
            {},
        )

        return len(records)
    
    async def record_event(
        self,
        event,
    ) -> bool:
        """
        پیام جدید را به Timeline اضافه می‌کند.
        اگر Timeline این گروه هنوز load نشده باشد،
        کاری انجام نمی‌دهد.
        """

        group_id = getattr(
            event,
            "chat_id",
            None,
        )

        if group_id is None:
            return False

        if group_id not in self._timelines:
            return False
        message = self._unwrap_message(
            event
        )

        message_id = self._extract_message_id(
            message
        )


        if message_id is None:
            return False

        seen = self._timeline_seen.setdefault(
            group_id,
            set(),
        )

        if message_id in seen:
            return False

        if self._is_command_message(event):
            return False
        # اگه یه پلاگین دیگه (content_filter، spam_filter و ...) قبلاً
        # گفته بود این پیام حذف شده، به‌جای متن واقعیِ پیام همون دلیل
        # حذف رو تو Timeline می‌ذاریم.
        pending_reason = self._pending_deletions.get(
            group_id, {}
        ).pop(message_id, None)

        if pending_reason is not None:
            text = f"[پیام حذف شده: {pending_reason}]"
            media_type = None
        else:
            text, media_type = self._extract_message_content(message)

        sender_id = getattr(
            message,
            "sender_id",
            None,
        )

        if sender_id is not None:
            try:
                sender_id = int(sender_id)
            except Exception:
                sender_id = None

        sender_identity = await self._resolve_sender_identity(
            group_id,
            message,
            sender_id,
        )

        
        reply_to_id = await self._extract_reply_id(
            message
        )

        

        reply_preview = None

        if reply_to_id is not None:
            try:
                reply_to_id = int(reply_to_id)
            except Exception:
                reply_to_id = None

        # اگر target در Timeline نیست،
        # خود پیام target را می‌گیریم و داخل رکورد فعلی
        # به‌عنوان preview ذخیره می‌کنیم.
        #
        # این شامل Commandها هم می‌شود.
        if (
            reply_to_id is not None
            and reply_to_id not in seen
        ):
            replied = await self._get_reply_message(
                event
            )

            if replied is not None:
                reply_preview = (
                    await self._build_reply_preview(
                        group_id,
                        replied,
                    )
                )

        record = {
            "message_id": message_id,
            "group_id": group_id,
            **sender_identity,
            "type": "user",
            "text": text,
            "media": media_type,
            "date": self._format_date(
                getattr(
                    message,
                    "date",
                    None,
                )
            ),
            "reply_to_id": reply_to_id,
        }

        if reply_preview is not None:
            record["reply_preview"] = reply_preview

        self._insert_timeline_record(
            group_id,
            record,
        )
        return True


