    def _format_timeline_identity(
        self,
        record: dict[str, Any],
    ) -> str:
        attributes = []

        for key in (
            "nick_name",
            "user_name",
            "user_id",
        ):
            value = record.get(key)

            if value is None or value == "":
                continue

            attributes.append(
                f'{key}="{self._timeline_attribute(value)}"'
            )

        if not attributes:
            return ""

        return " " + " ".join(attributes)




    @staticmethod
    def _timeline_attribute(
        value: Any,
    ) -> str:
        return html.escape(
            str(value),
            quote=True,
        )

    def _format_timeline_record(
        self,
        record: dict[str, Any],
        by_id: dict[int, dict[str, Any]],
    ) -> str:

        message_id = self._timeline_attribute(
            record["message_id"]
        )

        date = self._timeline_attribute(
            record["date"]
        )

        message_type = self._timeline_attribute(
            record.get("type", "user")
        )

        status = record.get(
            "status"
        )

        attributes = (
            f'id="{message_id}" '
            f'time="{date}"'
            f'{self._format_timeline_identity(record)} '
            f'type="{message_type}"'
        )
        if status:
            attributes += (
                f' status="{self._timeline_attribute(status)}"'
            )

        text = str(
            record.get(
                "text",
                "",
            )
        )

        result = (
            f"<message {attributes}>\n"
            "<text>\n"
            f"{text}\n"
            "</text>"
        )

        reply_to_id = record.get(
            "reply_to_id"
        )

        if reply_to_id is None:
            return (
                result
                + "\n</message>"
            )

        try:
            reply_to_id = int(
                reply_to_id
            )
        except Exception:
            return (
                result
                + "\n</message>"
            )

        target = by_id.get(
            reply_to_id
        )

        # target داخل Timeline است.
        if target is not None:
            target_id = self._timeline_attribute(
                target["message_id"]
            )

            target_date = self._timeline_attribute(
                target["date"]
            )



            target_type = self._timeline_attribute(
                target.get("type", "user")
            )

            target_text = str(
                target.get(
                    "text",
                    "",
                )
            )

            result += (
                "\n<reply_to "
                f'id="{target_id}" '
                f'time="{target_date}"'
                f'{self._format_timeline_identity(target)} '
                f'type="{target_type}">\n'
            )
            return (
                result
                + "\n</message>"
            )

        # target داخل Timeline نیست،
        # ولی snapshot آن را داریم.
        reply_preview = record.get(
            "reply_preview"
        )

        if reply_preview is not None:
            preview_id = self._timeline_attribute(
                reply_preview.get(
                    "message_id",
                    reply_to_id,
                )
            )

            preview_date = self._timeline_attribute(
                reply_preview.get(
                    "date",
                    "unknown",
                )
            )

            preview_identity = (
                self._format_timeline_identity(
                    reply_preview
                )
            )

            preview_type = self._timeline_attribute(
                reply_preview.get(
                    "type",
                    "user",
                )
            )

            preview_text = str(
                reply_preview.get(
                    "text",
                    "",
                )
            )

            result += (
                "\n<reply_to "
                f'id="{preview_id}" '
                f'time="{preview_date}"'
                f'{preview_identity} '
                f'type="{preview_type}" '
                'source="snapshot">\n'
                "<text>\n"
                f"{preview_text}\n"
                "</text>\n"
                "</reply_to>"
            )

            return (
                result
                + "\n</message>"
            )

        # رابطه مشخص است، ولی متن target در دسترس نیست.
        result += (
            "\n<reply_to "
            f'id="{self._timeline_attribute(reply_to_id)}" '
            'source="unavailable" />'
        )

        return (
            result
            + "\n</message>"
        )
    
    def get_timeline_context(
        self,
        group_id: int,
    ) -> str | None:

        timeline = self._timelines.get(
            group_id
        )

        if not timeline:
            return None

        records = list(timeline)

        by_id = {
            int(record["message_id"]): record
            for record in records
        }

        selected: list[dict[str, Any]] = []

        total_chars = 0

        for record in reversed(records):

            formatted = self._format_timeline_record(
                record,
                by_id,
            )

            if (
                selected
                and (
                    len(selected)
                    >= self.TIMELINE_CONTEXT_MESSAGES
                    or
                    total_chars + len(formatted)
                    > self.TIMELINE_CONTEXT_CHARS
                )
            ):
                break

            selected.append(record)
            total_chars += len(formatted)

        selected.reverse()

        lines = [
            "<timeline>",
        ]

        for record in selected:
            lines.append(
                self._format_timeline_record(
                    record,
                    by_id,
                )
            )

        lines.append(
            "</timeline>"
        )

        return "\n".join(lines)
